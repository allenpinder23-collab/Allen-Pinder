import Link from "next/link";
import { notFound } from "next/navigation";
import { prisma } from "@/lib/db";
import PageHeader from "@/components/PageHeader";
import StatusBadge from "@/components/StatusBadge";
import ClientStatusControl from "@/components/ClientStatusControl";
import { formatCurrency, formatDate } from "@/lib/format";

export default async function ClientDetailPage({
  params,
}: {
  params: Promise<{ id: string }>;
}) {
  const { id } = await params;

  const client = await prisma.client.findUnique({
    where: { id },
    include: {
      createdBy: { select: { name: true } },
      plans: {
        orderBy: { createdAt: "desc" },
        include: { generatedBy: { select: { name: true } } },
      },
    },
  });

  if (!client) notFound();

  return (
    <>
      <PageHeader
        title={client.fullName}
        description={`Added ${formatDate(client.createdAt.toISOString())} by ${client.createdBy.name}`}
        action={
          <div className="flex items-center gap-3">
            <ClientStatusControl clientId={client.id} status={client.status} />
            <Link
              href={`/clients/${client.id}/analyze`}
              className="rounded-lg bg-indigo-600 px-4 py-2 text-sm font-semibold text-white shadow-sm shadow-indigo-600/20 transition-colors hover:bg-indigo-500"
            >
              Generate new plan
            </Link>
          </div>
        }
      />

      <div className="flex-1 space-y-6 px-6 py-6 md:px-8">
        <div className="grid grid-cols-1 gap-6 lg:grid-cols-3">
          <div className="rounded-xl border border-slate-200 bg-white p-5 shadow-sm">
            <h2 className="text-xs font-semibold uppercase tracking-wide text-slate-500">Profile</h2>
            <dl className="mt-3 space-y-2 text-sm">
              <div className="flex justify-between gap-4">
                <dt className="text-slate-500">Status</dt>
                <dd>
                  <StatusBadge status={client.status} />
                </dd>
              </div>
              <div className="flex justify-between gap-4">
                <dt className="text-slate-500">Email</dt>
                <dd className="text-slate-900">{client.email || "—"}</dd>
              </div>
              <div className="flex justify-between gap-4">
                <dt className="text-slate-500">Phone</dt>
                <dd className="text-slate-900">{client.phone || "—"}</dd>
              </div>
            </dl>
            {client.notes && (
              <>
                <h3 className="mt-4 text-xs font-semibold uppercase tracking-wide text-slate-500">
                  Notes
                </h3>
                <p className="mt-1.5 whitespace-pre-wrap text-sm text-slate-700">{client.notes}</p>
              </>
            )}
          </div>

          <div className="lg:col-span-2 rounded-xl border border-slate-200 bg-white p-5 shadow-sm">
            <h2 className="text-xs font-semibold uppercase tracking-wide text-slate-500">
              Plan history
            </h2>
            {client.plans.length === 0 ? (
              <div className="mt-4 rounded-lg border border-dashed border-slate-300 px-4 py-8 text-center">
                <p className="text-sm text-slate-500">
                  No plans generated yet for this client.
                </p>
                <Link
                  href={`/clients/${client.id}/analyze`}
                  className="mt-3 inline-block text-sm font-medium text-indigo-600 hover:text-indigo-500"
                >
                  Generate the first plan &rarr;
                </Link>
              </div>
            ) : (
              <ul className="mt-3 divide-y divide-slate-100">
                {client.plans.map((plan) => (
                  <li key={plan.id}>
                    <Link
                      href={`/clients/${client.id}/plans/${plan.id}`}
                      className="flex items-center justify-between gap-4 py-3 hover:bg-slate-50/80 -mx-2 px-2 rounded-lg transition-colors"
                    >
                      <div>
                        <p className="text-sm font-medium text-slate-900">
                          {formatDate(plan.createdAt.toISOString())}
                        </p>
                        <p className="text-xs text-slate-500">
                          Generated by {plan.generatedBy.name}
                        </p>
                      </div>
                      <div className="text-right">
                        <p className="text-sm font-medium text-slate-900">
                          {plan.scoreRangeLabel ?? "—"}
                        </p>
                        <p className="text-xs text-slate-500">
                          {plan.monthlyCashFlow !== null
                            ? `${formatCurrency(plan.monthlyCashFlow)} / mo cash flow`
                            : ""}
                        </p>
                      </div>
                    </Link>
                  </li>
                ))}
              </ul>
            )}
          </div>
        </div>
      </div>
    </>
  );
}
